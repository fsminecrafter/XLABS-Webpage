/* Draws text into an ARGB8888 surface. `scale` makes each font pixel a
 * scale x scale block. Returns the x position after the last character. */
static int draw_text(uint32_t* pixels, int width, int height, int x, int y,
                     const char* text, uint32_t color, int scale) {
    int cx = x;
    for (; *text; text++) {
        if (*text == '\n') { cx = x; y += 10 * scale; continue; }
        unsigned char c = (unsigned char)*text;
        const uint8_t* glyph = font8x8[c < 128 ? c : '?'];
        for (int gy = 0; gy < 8; gy++) {
            for (int gx = 0; gx < 8; gx++) {
                if (!(glyph[gy] & (1 << gx))) continue;
                for (int sy = 0; sy < scale; sy++) {
                    int py = y + gy * scale + sy;
                    if (py < 0 || py >= height) continue;
                    for (int sx = 0; sx < scale; sx++) {
                        int px = cx + gx * scale + sx;
                        if (px >= 0 && px < width) pixels[py * width + px] = color;
                    }
                }
            }
        }
        cx += 8 * scale;
    }
    return cx;
}

static int text_width(const char* text, int scale) {
    int n = 0;
    while (text[n] && text[n] != '\n') n++;
    return n * 8 * scale;
}

