#!/usr/bin/env node
// Regenerates studio/templates.js from studio/templates/<id>/ and
// templates/_shared (shared files are added to a template that includes them).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'templates');
const list = JSON.parse(readFileSync(join(root, 'index.json'), 'utf8'));
const shared = Object.fromEntries(readdirSync(join(root, '_shared')).map(f => [f, readFileSync(join(root, '_shared', f), 'utf8')]));
for (const t of list) {
  t.files = {};
  for (const f of readdirSync(join(root, t.id))) t.files[f] = readFileSync(join(root, t.id, f), 'utf8');
  for (const [name, src] of Object.entries(shared)) {
    if (Object.values(t.files).some(s => s.includes('"' + name + '"'))) t.files[name] = src;
  }
}
writeFileSync(join(root, '..', 'templates.js'),
  '// Generated by studio/tools/build-templates.mjs from studio/templates. Do not edit.\nwindow.STUDIO_TEMPLATES = ' + JSON.stringify(list, null, 1) + ';\n');
console.log('templates.js: ' + list.map(t => t.id + '(' + Object.keys(t.files).length + ')').join(' '));
