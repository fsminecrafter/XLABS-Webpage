#!/usr/bin/env node
// Regenerates studio/sdk.js from a Minimal-OS-SDK checkout.
//
//   node studio/tools/build-sdk.mjs path/to/Minimal-OS-SDK
//
// The headers are copied as they are, except for the three inline-asm
// syscall stubs: the Studio compiler has no inline assembler, so their
// bodies become the __syscall(number, a, b, c) builtin. It compiles to the
// same `int $0x80` in a .run build and to the kernel emulation in the
// browser preview.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const sdkRoot = process.argv[2];
if (!sdkRoot) { console.error('usage: build-sdk.mjs <Minimal-OS-SDK>'); process.exit(2); }
const include = join(sdkRoot, 'include');
const here = dirname(fileURLToPath(import.meta.url));

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (/\.h$/.test(name) || !name.includes('.')) out.push(p);   // C headers, and C++ ones like <iostream>
  }
  return out;
}

// Replace the body of `static inline <ret> <name>(...) { ... }` with `body`.
function replaceBody(src, name, body) {
  const at = src.search(new RegExp('\\b' + name + '\\s*\\('));
  if (at < 0) throw new Error('function ' + name + ' not found');
  const open = src.indexOf('{', at);
  let depth = 0, i = open;
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) break;
  }
  return src.slice(0, open) + '{\n    ' + body + '\n}' + src.slice(i + 1);
}

const files = {};
for (const p of walk(include)) {
  const rel = relative(include, p).split('\\').join('/');
  if (/\.orig$/.test(rel)) continue;
  let src = readFileSync(p, 'utf8');
  // (mos_syscall lived in minimalos.h before the SDK's user_common.h existed)
  const stubs = {
    'minimalos.h': ['mos_syscall', 'return (long)__syscall(num, a1, a2, a3);'],
    'x86_64/user_common.h': ['mos_syscall', 'return (long)__syscall(num, a1, a2, a3);'],
    'window.h': ['mos_window_call', 'return __syscall(SYS_WINDOW, (uint64_t)(uintptr_t)request, 0, 0);'],
    'x86_64/user_syscalls.h': ['mos_syscall3', 'return __syscall(number, arg1, arg2, arg3);'],
  };
  if (stubs[rel] && new RegExp('\\b' + stubs[rel][0] + '\\s*\\(').test(src) && /\bint \$0x80/.test(src)) src = replaceBody(src, stubs[rel][0], stubs[rel][1]);
  // FarcadeGL's square root is one SSE instruction; in plain C it is a
  // bit-level first guess refined by Newton steps (exact to float precision).
  if (rel === 'farcadegl.h' && /sqrtss/.test(src)) src = replaceBody(src, 'fglSqrt',
    'if (x <= 0.0f) return 0.0f;\n    union { float f; uint32_t u; } g;\n    g.f = x;\n    g.u = (g.u >> 1) + 0x1fbd1df5u;\n' +
    '    float r = g.f;\n    for (int i = 0; i < 4; i++) r = 0.5f * (r + x / r);\n    return r;');
  if (/\basm\b|__asm__/.test(src.replace(/\/\/.*|\/\*[\s\S]*?\*\//g, ''))) throw new Error(rel + ' still contains inline assembly');
  files[rel] = src;
}

// Freestanding C headers and the crt0 the compiler links into every program.
const builtinDir = join(here, 'builtin');
for (const p of walk(builtinDir).concat([join(builtinDir, 'crt0.c')]).filter((v, i, a) => a.indexOf(v) === i)) files[relative(builtinDir, p).split('\\').join('/')] = readFileSync(p, 'utf8');

const out = '// Generated by studio/tools/build-sdk.mjs from Minimal-OS-SDK/include. Do not edit.\n' +
  '(function (G) { (G.MCC || (G.MCC = {})).SDK = ' + JSON.stringify(files, null, 0) + '; })(typeof self !== \'undefined\' ? self : globalThis);\n';
writeFileSync(join(here, '..', 'sdk.js'), out);
console.log('sdk.js: ' + Object.keys(files).length + ' files');
